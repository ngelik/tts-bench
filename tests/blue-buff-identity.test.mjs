import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import test from 'node:test';
import assert from 'node:assert/strict';
import { BLUE_BUFF } from '../web/adapters/blue-buff-profile.mjs';
import { BLUE_BUFF_UPSTREAM, blueBuffSupportSources } from '../web/adapters/blue-buff-upstream.mjs';

test('Blue-Buff checkpoint and source keep their distinct upstream identities', () => {
  assert.equal(BLUE_BUFF.modelId, 'songLucasXXX/tiny-voca-zh');
  assert.equal(BLUE_BUFF.modelRevision, '9d6b4631bd59b1fa69b398913b852d03f22071d2');
  assert.equal(BLUE_BUFF.sourceId, 'blue-buff/tiny-voca-zh');
  assert.equal(BLUE_BUFF.sourceRevision, '8b3fb5b460e828a90913edc28f3f1ddc51a66127');
  assert.notEqual(BLUE_BUFF_UPSTREAM.model.id, BLUE_BUFF_UPSTREAM.source.id);
  assert.notEqual(BLUE_BUFF_UPSTREAM.model.revision, BLUE_BUFF_UPSTREAM.source.revision);
  assert.deepEqual(blueBuffSupportSources(), [
    'https://huggingface.co/songLucasXXX/tiny-voca-zh/tree/9d6b4631bd59b1fa69b398913b852d03f22071d2',
    'https://github.com/blue-buff/tiny-voca-zh/tree/8b3fb5b460e828a90913edc28f3f1ddc51a66127',
  ]);
});

assert.equal(BLUE_BUFF.framePlan.policy, 'zh-natural-boundary-v1');
assert.equal(BLUE_BUFF.framePlan.tokenTarget, 240);
assert.equal(BLUE_BUFF.framePlan.noiseReset, 'per-outer-span');

const frontendNoticeBytes = await readFile(new URL('../web/tiny-voca-zh-blue-buff/notices/manifest.json', import.meta.url));
const frontendNotice = JSON.parse(frontendNoticeBytes);
assert.equal(BLUE_BUFF.frontendZip.sha256, frontendNotice.frontendArchiveSha256);
assert.equal(BLUE_BUFF.frontendZip.bytes, 3461659);
assert.equal(BLUE_BUFF.frontendNotices['frontend-notices/manifest.json'][0], frontendNoticeBytes.length);
assert.equal(BLUE_BUFF.frontendNotices['frontend-notices/manifest.json'][1], createHash('sha256').update(frontendNoticeBytes).digest('hex'));
assert.deepEqual(frontendNotice.framePlanPolicy, {
  id: BLUE_BUFF.framePlan.policy, version: BLUE_BUFF.framePlan.policyVersion,
  module: BLUE_BUFF.framePlan.policyModule, sha256: 'da40affe377b8fb79d54d7620ba0793eb2afe902edca0aa862738fddab52db51',
  citation: frontendNotice.framePlanPolicy.citation,
});

test('published generated asset receipts name the portable build entrypoint', async () => {
  const finalizer = await readFile(new URL('../tools/finalize-blue-buff-lock.mjs', import.meta.url), 'utf8');
  assert.match(finalizer, /Generated by tools\/build-blue-buff\/build\.py/);
  assert.match(finalizer, /Built by tools\/build-blue-buff\/build\.py/);
  assert.doesNotMatch(finalizer, /Generated by tools\/build-blue-buff\/(?:from|using)/);
});
