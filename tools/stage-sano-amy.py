"""Prepare the two Sano Amy browser bundles from their original pinned Hugging Face packages."""
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.request import urlopen

REVISION = '25410576d005d7f08d186990fd91f6a2651243de'
VOICES = {'sano-amy-small': 'amy-en-1p1m', 'sano-amy-1p8m': 'amy-en-1p8m'}
INPUTS = ('manifest.json', 'weights.fp16.bin', 'piper-phoneme-config.json')
OUTPUTS = {'meta.json', 'front_f32.bin', 'dec_f32.bin'}


def stage(repo, model, local=None):
    voice = VOICES[model]
    tools = Path(__file__).resolve().parent
    with tempfile.TemporaryDirectory(prefix='sano-amy-') as work:
        work = Path(work)
        source = local if local else work/voice
        if local is None:
            source.mkdir()
            for name in INPUTS:
                url = f'https://huggingface.co/ampixa/sanoTTS/resolve/{REVISION}/{voice}/{name}'
                with urlopen(url, timeout=90) as response, (source/name).open('wb') as file:
                    shutil.copyfileobj(response, file)
        built = work/'built'
        subprocess.run([sys.executable, str(tools/'pack-sano-amy.py'), str(source), str(built)], check=True)
        assets = json.loads((repo/'assets.lock.json').read_text())['models'][model]['assets']
        # Resolve only the exact three local model targets declared by the reviewed registration.
        targets = [(asset, Path(asset['target'])) for asset in assets
                   if Path(asset['target']).name in OUTPUTS and asset['target'].startswith(f'models/{model}/')]
        if len(targets) != len(OUTPUTS) or {p.name for _, p in targets} != OUTPUTS:
            raise ValueError('Expected one registered target per generated file')
        cache = (repo/'.cache/public').resolve()
        for asset, path in targets:
            data = (built/path.name).read_bytes()
            if len(data) != asset['bytes'] or hashlib.sha256(data).hexdigest() != asset['sha256']:
                raise ValueError(f'Generated bytes differ from assets.lock.json: {path}')
            dest = (cache/path).resolve()
            if not dest.is_relative_to(cache):
                raise ValueError(f'Target outside public asset cache: {path}')
            dest.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=dest.parent, delete=False) as f:
                stage_file = Path(f.name)
                try:
                    f.write(data)
                    f.flush()
                    os.replace(stage_file, dest)
                finally:
                    stage_file.unlink(missing_ok=True)
            print(f'Staged {path}')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--model', required=True, choices=VOICES)
    p.add_argument('--repo', type=Path, default=Path(__file__).resolve().parent.parent)
    p.add_argument('--package-dir', type=Path, help='Use an already downloaded pinned voice package')
    args = p.parse_args()
    stage(args.repo.resolve(), args.model, args.package_dir)
